/** Props for `react-loader-spinner` ThreeDots wrapper. */
export interface DotsLoaderProps {
  /** Passed to the spinner as `wrapperClass`. */
  wrapperClassName?: string;
  /** Dot color (CSS color value). */
  mainColor?: string;
  /** Spinner width in px. */
  width?: number;
  /** Spinner height in px. */
  height?: number;
}
